/* Offline manifest compilation only. The game never calls an image service. */
'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),dir=path.join(root,'game/assets/avatar-raster');
const names=['bach','heads','fruit','milestone','classic','wish','knowledge'];
const manifest={version:1,revision:'20261102-stage4-layered',atlases:{},kits:{},heads:{},hands:{},defaults:Object.fromEntries(['shirt','pants','shoes'].map(slot=>[slot,'bach'])),catalog:{}};
for(const name of names){
  const part=JSON.parse(fs.readFileSync(path.join(dir,name+'-parts.json'),'utf8'));
  for(const section of ['atlases','kits','heads','catalog'])for(const [id,value] of Object.entries(part[section]||{})){
    assert(!(id in manifest[section]),'Duplicate '+section+' entry: '+id);manifest[section][id]=value;
  }
}
const longCoats=JSON.parse(fs.readFileSync(path.join(dir,'bach-long-parts.json'),'utf8'));
for(const [id,atlas] of Object.entries(longCoats.atlases)){assert(!manifest.atlases[id],id);manifest.atlases[id]=atlas;}
for(const [kit,variants] of Object.entries(longCoats.bodyVariants)){assert(manifest.kits[kit],kit);Object.assign(manifest.kits[kit].bodyVariants||(manifest.kits[kit].bodyVariants={}),variants);}
for(const direction of ['down','up','right','left']){
  manifest.hands[direction]={};
  for(const side of ['L','R']){
    const part=manifest.kits.bach.views[direction].parts['hand.'+side];
    assert(part,'Missing base hand '+direction+' '+side);manifest.hands[direction][side]=part;
  }
}
const A=require('../game/academy.js'),R=require('../game/adventure.js'),E=require('../game/engine.js'),M=require('../game/raster-outfit.js');
const catalog=[...R.GEAR,...E.ITEMS.map(item=>({...item,slot:'handheld'}))];
assert.deepEqual(Object.keys(manifest.catalog).sort(),catalog.map(item=>item.id).sort(),'Every sold/earned item needs its actual wearable artwork.');
for(const character of A.CHARACTERS)for(const direction of M.DIRECTIONS){
  const state={appearance:{character:character.id},rpg:{loadout:{}}};M.plan(state,direction,manifest,{MindAcademy:A,MindAdventure:R,MindEngine:E});
}
for(const item of catalog)for(const direction of M.DIRECTIONS)M.plan({appearance:{character:'doctor'},rpg:{loadout:{[item.slot]:item.id}}},direction,manifest,{MindAcademy:A,MindAdventure:R,MindEngine:E},item.slot);
const code="/* Generated by tools/build-raster-art.cjs from reviewed original raster parts. */\n(function(root,factory){const art=factory();if(typeof module==='object'&&module.exports)module.exports=art;else root.MindRasterArt=art;})(typeof window==='object'?window:globalThis,function(){return "+JSON.stringify(manifest)+";});\n";
fs.writeFileSync(path.join(root,'game/raster-art.js'),code);
console.log(JSON.stringify({items:catalog.length,heads:A.CHARACTERS.length*4,atlases:Object.keys(manifest.atlases).length,kits:Object.keys(manifest.kits).length,bytes:Buffer.byteLength(code)}));
